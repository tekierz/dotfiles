func TestReviewedInstallerWritesLazyGitToAcceptedConfigDirTarget(t *testing.T) {
	home := withTempHome(t)
	dir := filepath.Join(home, "reviewed", "lazygit")
	t.Setenv("CONFIG_DIR", dir)
	t.Setenv("LG_CONFIG_FILE", "")
	installed := make(map[string]bool)
	for _, tool := range tools.GetRegistry().All() {
		installed[tool.ID()] = true
	}
	app, installRuntime := newLazyGitPlanApp(t, home, installed)
	app.deepDiveConfig.LazyGitSidePanelWidth = "0.5"
	plan, err := buildInstallPlan(app, installRuntime, time.Now())
	if err != nil {
		t.Fatal(err)
	}
	wantRel := "reviewed/lazygit/config.yml"
	if action := planActionByID(t, plan, "config:lazygit"); !slices.Equal(action.BackupTargets, []string{wantRel}) {
		t.Fatalf("action=%+v", action)
	}
	keep := map[string]bool{"state:parents": true, "state:global": true, "config:lazygit": true}
	var actions []operation.Action
	authority := make(map[string]map[string]acceptedTarget)
	for _, action := range plan.actions() {
		if keep[action.ID] || action.Kind == operation.KindInstallFile {
			actions = append(actions, action)
			authority[action.ID] = plan.authority[action.ID]
		}
	}
	document, err := operation.NewPlan(time.Now(), actions)
	if err != nil {
		t.Fatal(err)
	}
	reviewed := &installPlan{
		document: document, configTools: []string{"lazygit"}, config: plan.config,
		theme: plan.theme, navStyle: plan.navStyle, animations: plan.animations,
		globalConfig: plan.globalConfig, authority: authority, parentDirs: plan.parentDirs,
		statePlan: plan.statePlan,
	}
	installRuntime.backupTargetsWithState = backupPlanTargetsWithState
	installRuntime.backupTargets = nil
	events := make(chan installEventMsg, 256)
	runInstallWorkerFromPlanWithRuntime(context.Background(), events, reviewed, installRuntime, true)
	var terminal installEventMsg
	for event := range events {
		if event.done {
			terminal = event
		}
	}
	if terminal.err != nil {
		t.Fatalf("reviewed installer result=%v\n%s", terminal.err, terminal.context)
	}
	content, err := os.ReadFile(filepath.Join(home, filepath.FromSlash(wantRel)))
	if err != nil || !tools.IsManagedLazyGitConfigContent(content) || !strings.Contains(string(content), "sidePanelWidth: 0.5") {
		t.Fatalf("managed bytes=%q err=%v", content, err)
	}
	if _, err := os.Stat(filepath.Join(home, ".config", "lazygit", "config.yml")); !os.IsNotExist(err) {
		t.Fatalf("installer wrote inactive fallback: %v", err)
	}
}

func TestLazyGitDeltaDependencyGatesInstallerAndEditors(t *testing.T) {
	home := withTempHome(t)
	t.Setenv("CONFIG_DIR", filepath.Join(home, ".config", "lazygit"))
	t.Setenv("LG_CONFIG_FILE", "")
	app, rt := newLazyGitPlanApp(t, home, map[string]bool{})
	app.deepDiveConfig.LazyGitPagerPreset = "delta"
	app.deepDiveConfig.CLIUtilities["delta"] = false
	plan, err := buildInstallPlan(app, rt, time.Now())
	if err != nil {
		t.Fatal(err)
	}
	if action := planActionByID(t, plan, "config:lazygit"); action.Disposition != operation.DispositionBlocked || !strings.Contains(action.Reason, "select the Delta") {
		t.Fatalf("disabled Delta action=%+v", action)
	}
	app.deepDiveConfig.CLIUtilities["delta"] = true
	plan, err = buildInstallPlan(app, rt, time.Now())
	if err != nil {
		t.Fatal(err)
	}
	if action := planActionByID(t, plan, "config:lazygit"); action.Disposition != operation.DispositionApply {
		t.Fatalf("planned Delta action=%+v", action)
	}
	if action := planActionByID(t, plan, "install:delta"); action.Disposition != operation.DispositionApply {
		t.Fatalf("Delta dependency action=%+v", action)
	}

	app.startScreen = ScreenConfigLazyGit
	app.manageInstalledReady = false
	if reason := lazyGitDeltaAvailabilityReason(app); !strings.Contains(reason, "not ready") {
		t.Fatalf("not-ready reason=%q", reason)
	}
	app.manageInstalledReady = true
	if reason := lazyGitDeltaAvailabilityReason(app); !strings.Contains(reason, "install the Delta") {
		t.Fatalf("missing reason=%q", reason)
	}
	app.manageInstalled["delta"] = true
	if reason := lazyGitDeltaAvailabilityReason(app); reason != "" {
		t.Fatalf("installed reason=%q", reason)
	}
	standalone, err := buildStandaloneConfigPlan(app, time.Now())
	if err != nil || standalone.hasBlocked() {
		t.Fatalf("installed standalone blocked=%v err=%v", standalone != nil && standalone.hasBlocked(), err)
	}
}

