func TestLazyGitPlanTargetPrecedence(t *testing.T) {
	home := withTempHome(t)
	t.Setenv("LG_CONFIG_FILE", "")
	t.Run("CONFIG_DIR", func(t *testing.T) {
		dir := filepath.Join(home, "config-dir")
		t.Setenv("CONFIG_DIR", dir)
		t.Setenv("XDG_CONFIG_HOME", filepath.Join(home, "xdg"))
		got, reason := lazyGitPlanTarget(home)
		if got != "config-dir/config.yml" || reason != "" {
			t.Fatalf("target=%q reason=%q", got, reason)
		}
	})
	t.Run("XDG", func(t *testing.T) {
		t.Setenv("CONFIG_DIR", "")
		t.Setenv("XDG_CONFIG_HOME", filepath.Join(home, "xdg"))
		got, reason := lazyGitPlanTarget(home)
		if got != "xdg/lazygit/config.yml" || reason != "" {
			t.Fatalf("target=%q reason=%q", got, reason)
		}
	})
	t.Run("platform default", func(t *testing.T) {
		t.Setenv("CONFIG_DIR", "")
		t.Setenv("XDG_CONFIG_HOME", "")
		got, reason := lazyGitPlanTarget(home)
		want := ".config/lazygit/config.yml"
		if runtime.GOOS == "darwin" {
			want = "Library/Application Support/lazygit/config.yml"
		}
		if got != want || reason != "" {
			t.Fatalf("target=%q want=%q reason=%q", got, want, reason)
		}
	})
}

func TestLazyGitPlannerBlocksUnsafeNativeSourcesWithExactReason(t *testing.T) {
	tests := []struct {
		name string
		body []byte
		want string
	}{
		{"arbitrary", []byte("gui:\n  mouseEvents: false\ncustom: keep\n"), "arbitrary native LazyGit YAML"},
		{"legacy generated", []byte("# Generated by dotfiles TUI\ngui:\n  mouseEvents: true\n"), "arbitrary native LazyGit YAML"},
		{"custom pager", []byte("git:\n  pagers:\n    - pager: less\n"), "custom LazyGit pagers"},
		{"malformed", []byte("gui: [\n"), "could not be imported safely"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			home := withTempHome(t)
			dir := filepath.Join(home, ".config", "lazygit")
			t.Setenv("CONFIG_DIR", dir)
			t.Setenv("LG_CONFIG_FILE", "")
			if err := os.MkdirAll(dir, 0o700); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(dir, "config.yml")
			if err := os.WriteFile(path, tc.body, 0o600); err != nil {
				t.Fatal(err)
			}
			app, rt := newLazyGitPlanApp(t, home, map[string]bool{"delta": true})
			plan, err := buildInstallPlan(app, rt, time.Now())
			if err != nil {
				t.Fatal(err)
			}
			action := planActionByID(t, plan, "config:lazygit")
			if action.Disposition != operation.DispositionBlocked || !strings.Contains(action.Reason, tc.want) {
				t.Fatalf("action=%+v", action)
			}
			if got, err := os.ReadFile(path); err != nil || !bytes.Equal(got, tc.body) {
				t.Fatalf("preview mutated bytes=%q err=%v", got, err)
			}
		})
	}
}

