func prepareNativeYaziUI(t *testing.T) string {
	t.Helper()
	home := withTempHome(t)
	t.Setenv("YAZI_CONFIG_HOME", "")
	t.Setenv("CONFIG_DIR", "")
	t.Setenv("LG_CONFIG_FILE", "")
	dir := filepath.Join(home, ".config", "yazi")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	return dir
}

func writeNativeYaziUI(t *testing.T, dir, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func explicitYaziPreferences(err error) managePreferencePresence {
	fields := map[string]bool{}
	for _, field := range yaziManageFields {
		fields[field] = true
	}
	return managePreferencePresence{exists: true, fields: fields, schema: 6, err: err}
}

func savedYaziPreferences() *ManageConfig {
	target := NewManageConfig()
	target.YaziKeymap = "vim"
	target.YaziShowHidden = false
	target.YaziPreviewMode = "auto"
	target.YaziSortBy = "alphabetical"
	target.YaziSortReverse = false
	target.YaziLineMode = "none"
	target.YaziScrollOff = 3
	return target
}

func assertSavedYaziPreferences(t *testing.T, got *ManageConfig) {
	t.Helper()
	assertYaziValues(t, got, "vim", false, "auto", "alphabetical", false, "none", 3)
}

func assertYaziValues(t *testing.T, got *ManageConfig, keymap string, hidden bool, preview, sort string, reverse bool, line string, scroll int) {
	t.Helper()
	if got.YaziKeymap != keymap || got.YaziShowHidden != hidden || got.YaziPreviewMode != preview || got.YaziSortBy != sort || got.YaziSortReverse != reverse || got.YaziLineMode != line || got.YaziScrollOff != scroll {
		t.Fatalf("Yazi values = %+v; want %s/%t/%s/%s/%t/%s/%d", got, keymap, hidden, preview, sort, reverse, line, scroll)
	}
}

