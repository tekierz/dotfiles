func TestNeovimReviewedOverlayUsesLegacyToolConfigLockProtocol(t *testing.T) {
	authority := seedNeovimOverlayAuthority(t, []byte("-- user init\n"), nil, true)
	release, err := operation.DefaultLocker("tool-config", authority.initPath)
	if err != nil {
		t.Fatal(err)
	}
	done := make(chan error, 1)
	go func() {
		_, err := WriteNeovimUserPrefsAtBoundAuthoritiesTracked(NeovimConfig{}, "dracula", authority.initRevision, authority.initParents, authority.optionsRevision, authority.optionsParents, operation.DefaultLocker)
		done <- err
	}()
	select {
	case err := <-done:
		t.Fatalf("reviewed overlay did not wait for legacy lock: %v", err)
	case <-time.After(100 * time.Millisecond):
	}
	if err := release(); err != nil {
		t.Fatal(err)
	}
	if err := <-done; err != nil {
		t.Fatal(err)
	}
}
