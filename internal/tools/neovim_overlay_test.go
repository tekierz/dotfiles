func TestNeovimReviewedOverlaySecondWriteFailureReturnsOptionsEvidence(t *testing.T) {
	authority := seedNeovimOverlayAuthority(t, []byte("-- user init\n"), nil, true)
	actual := neovimAuthorizedReplace(safefile.ReplaceWithinRevisionNoCreateAuthorizedTracked)
	failure := errors.New("injected init replacement failure")
	calls := 0
	replace := func(root, rel string, accepted safefile.Revision, parents *safefile.ParentChain, content []byte, mode os.FileMode) (safefile.Revision, error) {
		calls++
		if calls == 2 {
			return safefile.Revision{}, failure
		}
		return actual(root, rel, accepted, parents, content, mode)
	}
	_, err := writeNeovimUserPrefsAtBoundAuthoritiesTracked(NeovimConfig{TabWidth: 2}, "dracula", authority.initRevision, authority.initParents, authority.optionsRevision, authority.optionsParents, noopCountingLocker(new(int), new(int)), replace)
	var partial *PartialMutationError
	if !errors.Is(err, failure) || !errors.As(err, &partial) || len(partial.Evidence) != 1 || partial.Evidence[0].Path != authority.optionsPath {
		t.Fatalf("error=%v partial=%+v", err, partial)
	}
	initContent, _ := os.ReadFile(authority.initPath)
	if strings.Contains(string(initContent), neovimManagedStart) {
		t.Fatalf("failed init replacement changed init.lua:\n%s", initContent)
	}
}

func TestNeovimReviewedOverlayCommittedInitFailureReturnsBothEvidence(t *testing.T) {
	authority := seedNeovimOverlayAuthority(t, []byte("-- user init\n"), nil, true)
	actual := neovimAuthorizedReplace(safefile.ReplaceWithinRevisionNoCreateAuthorizedTracked)
	failure := errors.New("injected init postcommit failure")
	calls := 0
	replace := func(root, rel string, accepted safefile.Revision, parents *safefile.ParentChain, content []byte, mode os.FileMode) (safefile.Revision, error) {
		calls++
		revision, err := actual(root, rel, accepted, parents, content, mode)
		if err == nil && calls == 2 {
			return revision, &safefile.CommittedError{Operation: "injected init validation", Err: failure}
		}
		return revision, err
	}
	_, err := writeNeovimUserPrefsAtBoundAuthoritiesTracked(NeovimConfig{TabWidth: 2}, "dracula", authority.initRevision, authority.initParents, authority.optionsRevision, authority.optionsParents, noopCountingLocker(new(int), new(int)), replace)
	var partial *PartialMutationError
	if !errors.Is(err, failure) || !errors.As(err, &partial) || len(partial.Evidence) != 2 {
		t.Fatalf("error=%v partial=%+v", err, partial)
	}
}

