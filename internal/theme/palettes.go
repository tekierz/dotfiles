// Package theme holds the dotfiles color palettes as plain data (hex strings),
// with no dependency on internal/ui or internal/tools. Both the TUI (internal/ui)
// and the tool config generators (internal/tools) import it, so one palette
// definition drives unified theming across every tool. Do not import ui/tools here.
package theme

// Palette is one theme's colors as hex strings (e.g. "#1e1e2e"). Field roles
// mirror internal/ui.ColorPalette so the UI can build lipgloss colors from these.
type Palette struct {
	Accent     string // main accent (selections, highlights)
	AccentAlt  string // secondary accent
	Info       string // blue/info
	Success    string // green
	Warning    string // yellow
	Error      string // red
	Bg         string // main background
	Surface    string // elevated surface
	Overlay    string // popup background
	Border     string // borders
	Text       string // primary text
	TextMuted  string // muted text
	TextBright string // bright/emphasized text
}

